# How each Latin letter is read. Klingon only tells q from Q, so every
# other letter maps both cases to one glyph; letters Klingon lacks borrow
# the nearest sound. Romanized Klingon and plain English both come out.
LATIN = {
    'a': 'a', 'b': 'b', 'c': 'q', 'd': 'D', 'e': 'e', 'f': 'v', 'g': KL_GH,
    'h': 'H', 'i': 'I', 'j': 'j', 'k': 'q', 'l': 'l', 'm': 'm', 'n': 'n',
    'o': 'o', 'p': 'p', 'r': 'r', 's': 'S', 't': 't', 'u': 'u',
    'v': 'v', 'w': 'w', 'x': 'Q', 'y': 'y', 'z': 'S',
}


def parse(art):
    rows = art.strip('\n').split('\n')
    assert len(rows) == 12 and all(len(r) == 7 for r in rows), rows
    cell = [0, 0]
    for r in rows:
        cell.append(int(r.replace('.', '0').replace('#', '1') + '0', 2))
    return cell + [0, 0]


def main():
    font = [[0] * 16 for _ in range(256)]
    for ch, art in list(PUNCT.items()) + list(DIGITS.items()):
        font[ord(ch)] = parse(art)
    font[ord("'")] = parse(KLINGON["'"])
    for latin, kl in LATIN.items():
        glyph = parse(KLINGON[kl])
        font[ord(latin)] = glyph
        font[ord(latin.upper())] = glyph
    font[ord('q')] = parse(KLINGON['q'])
    font[ord('Q')] = parse(KLINGON['Q'])
    for cp in (KL_CH, KL_GH, KL_NG, KL_TLH):
        font[cp] = parse(KLINGON[cp])

    print('; Generated by tools/klingon-font.py; edit that, not this.')
    print('; 256 glyphs, 16 bytes each, for VGA plane 2.')
    print()
    print('KL_CH  equ 0x%02X' % KL_CH)
    print('KL_GH  equ 0x%02X' % KL_GH)
    print('KL_NG  equ 0x%02X' % KL_NG)
    print('KL_TLH equ 0x%02X' % KL_TLH)
    print()
    print('klingon_font:')
    for i, cell in enumerate(font):
        print('    db ' + ', '.join('0x%02X' % b for b in cell) + '  ; 0x%02X' % i)


if __name__ == '__main__':
    main()
