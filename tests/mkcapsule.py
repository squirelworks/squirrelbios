#!/usr/bin/env python3
"""Build signed SquirrelBIOS system-firmware capsules for Phase G smoke. Original code."""
import hashlib, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mksigned import (RSA_ENC, SHA256, certificate, guid, integer, name as name_der,
                      oid, rsa_key, seq, set_, sign, tlv)

SYSFW = guid("a7c4e9f2-3b1d-4e8a-9c55-12846f91de30")
PKCS7_GUID = guid("4aafd29d-68df-49ee-8aa9-347d375665a7")
SQCP_MAGIC, TARGET_VERSION, PERSIST = 0x50435153, 0x00020300, 0x00010000
BODY = b"SQUIRREL-FW-STUB\x00" + b"\x00" * 16
HEADER_SIZE = 28 + 16

def make_pkcs7(key, cert, issuer, serial, content_hash):
    attrs = (seq(oid("1.2.840.113549.1.9.3"), set_(oid("1.2.840.113549.1.7.1"))) +
             seq(oid("1.2.840.113549.1.9.4"), set_(tlv(0x04, content_hash))))
    signer = seq(integer(1), seq(name_der(issuer), integer(serial)), SHA256,
                 tlv(0xA0, attrs), RSA_ENC, tlv(0x04, sign(key, set_(attrs))))
    return seq(integer(1), set_(SHA256), seq(oid("1.2.840.113549.1.7.1")),
               tlv(0xA0, cert), set_(signer))

def capsule(key, cert, issuer, serial, flags=0):
    sq = struct.pack("<IIII", SQCP_MAGIC, TARGET_VERSION, len(BODY), 0)
    probe = make_pkcs7(key, cert, issuer, serial, b"\x00" * 32)
    win_len = 24 + len(probe)
    image_size = HEADER_SIZE + len(BODY) + win_len
    prefix = bytearray(SYSFW + struct.pack("<III", HEADER_SIZE, flags, image_size) + sq + BODY)
    sd = make_pkcs7(key, cert, issuer, serial, hashlib.sha256(prefix).digest())
    assert 24 + len(sd) == win_len
    win = struct.pack("<IHH", 24 + len(sd), 0x0200, 0x0EF1) + PKCS7_GUID + sd
    return bytes(prefix + win)

def c_header(name, data):
    lines = ["/* Generated by tests/mkcapsule.py — do not edit. */",
             f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+12]) + ",")
    lines += ["};", f"static const unsigned int {name}_len = {len(data)};", ""]
    return "\n".join(lines)

def main():
    out = sys.argv[1]; os.makedirs(out, exist_ok=True)
    key_a, key_b = rsa_key(0x5153_0001), rsa_key(0x5153_0002)
    cert_a = certificate(key_a, "SquirrelBIOS test key A", 0xA1)
    cert_b = certificate(key_b, "SquirrelBIOS test key B", 0xB2)
    a = (key_a, cert_a, "SquirrelBIOS test key A", 0xA1)
    b = (key_b, cert_b, "SquirrelBIOS test key B", 0xB2)
    good, bad, persist = capsule(*a), capsule(*b), capsule(*a, flags=PERSIST)
    open(os.path.join(out, "capsule-good.cap"), "wb").write(good)
    open(os.path.join(out, "capsule-bad.cap"), "wb").write(bad)
    open(os.path.join(out, "capsule-persist.cap"), "wb").write(persist)
    open(os.path.join(out, "capsule_good_blob.h"), "w").write(c_header("capsule_good_blob", good))
    open(os.path.join(out, "capsule_bad_blob.h"), "w").write(c_header("capsule_bad_blob", bad))
    open(os.path.join(out, "capsule_persist_blob.h"), "w").write(c_header("capsule_persist_blob", persist))
    print(f"wrote good={len(good)} bad={len(bad)} persist={len(persist)} to {out}")

if __name__ == "__main__":
    main()
