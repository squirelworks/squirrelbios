#!/usr/bin/env python3
"""Build signed SquirrelBIOS system-firmware capsules for Phase G smoke.

Original code. Two trust lanes:

  * Keys A/B (seeds 0x5153_0001 / 0x5153_0002) — Secure Boot / early
    capsule smokes (`capsule-good.cap`, `sb-db-x509.esl`).
  * Project capsule key (seed 0x5153_C001) — Phase G M4 product path
    (`capsule-project.cap`, `capsule-project.esl`). Private material is
    never committed; only the public X.509 DER and ESL are written under
    the build dir. Production keys stay off-tree.

    python3 tests/mkcapsule.py OUTDIR
    python3 tests/mkcapsule.py --sign-project OUT.cap
    python3 tests/mkcapsule.py --print-recipe
"""
import hashlib, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mksigned import (RSA_ENC, SHA256, CERT_X509, certificate, esl, guid,
                      integer, name as name_der, oid, rsa_key, seq, set_,
                      sign, tlv)

SYSFW = guid("a7c4e9f2-3b1d-4e8a-9c55-12846f91de30")
PKCS7_GUID = guid("4aafd29d-68df-49ee-8aa9-347d375665a7")
SQCP_MAGIC, TARGET_VERSION, PERSIST = 0x50435153, 0x00020400, 0x00010000
BODY = b"SQUIRREL-FW-STUB\x00" + b"\x00" * 16
HEADER_SIZE = 28 + 16

# Phase G M4: dedicated project capsule test key (not Secure Boot key A).
PROJECT_SEED = 0x5153_C001
PROJECT_CN = "SquirrelBIOS capsule project test key"
PROJECT_SERIAL = 0xC001

RECIPE = """\
SquirrelBIOS capsule project-key signing recipe (Phase G M4 / 2.2.50)
====================================================================

Public specs: UEFI 2.10 §8.5.3 UpdateCapsule, §4.6 ESRT, §8.2 detached
PKCS#7 / WIN_CERTIFICATE_UEFI_GUID. Original tooling; no OpenSSL / EDK2.

1. Generate fixtures (public cert + ESL + signed .cap) into a build dir:

     python3 tests/mkcapsule.py build/tests/sb

   Writes (among others):
     capsule-project.esl          trust ESL for fw_cfg capsule-db
     capsule-project-pub.der      public X.509 only (safe to commit from a
                                  release notes tree; smoke regenerates it)
     capsule-project.cap          SQCP capsule signed by the project key
     capsule_project_blob.h       C include for the guest stand-in

2. Sign a fresh capsule with the in-tree test project key (no private
   production key; seed 0x5153_C001 derives the RSA-2048 pair in process):

     python3 tests/mkcapsule.py --sign-project path/to/out.cap

3. QEMU smoke trust path:

     -fw_cfg name=opt/org.squirrelworks/capsule-db,file=capsule-project.esl

4. Host ESRT stand-in (fwupd-shaped list/update check against a serial log):

     python3 tools/esrt_standin.py build/tests/x86_64-capsule-key.log

Never commit private production keys or real SPI firmware images.
"""


def make_pkcs7(key, cert, issuer, serial, content_hash):
    attrs = (seq(oid("1.2.840.113549.1.9.3"), set_(oid("1.2.840.113549.1.7.1"))) +
             seq(oid("1.2.840.113549.1.9.4"), set_(tlv(0x04, content_hash))))
    signer = seq(integer(1), seq(name_der(issuer), integer(serial)), SHA256,
                 tlv(0xA0, attrs), RSA_ENC, tlv(0x04, sign(key, set_(attrs))))
    return seq(integer(1), set_(SHA256), seq(oid("1.2.840.113549.1.7.1")),
               tlv(0xA0, cert), set_(signer))


def capsule(key, cert, issuer, serial, flags=0):
    sq = struct.pack("<IIII", SQCP_MAGIC, TARGET_VERSION, len(BODY), 0)
    probe = make_pkcs7(key, cert, issuer, serial, b"\x00" * 32)
    win_len = 24 + len(probe)
    image_size = HEADER_SIZE + len(BODY) + win_len
    prefix = bytearray(SYSFW + struct.pack("<III", HEADER_SIZE, flags, image_size) + sq + BODY)
    sd = make_pkcs7(key, cert, issuer, serial, hashlib.sha256(prefix).digest())
    assert 24 + len(sd) == win_len
    win = struct.pack("<IHH", 24 + len(sd), 0x0200, 0x0EF1) + PKCS7_GUID + sd
    return bytes(prefix + win)


def project_key():
    key = rsa_key(PROJECT_SEED)
    cert = certificate(key, PROJECT_CN, PROJECT_SERIAL)
    return key, cert, PROJECT_CN, PROJECT_SERIAL


def c_header(name, data):
    lines = ["/* Generated by tests/mkcapsule.py — do not edit. */",
             f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
    lines += ["};", f"static const unsigned int {name}_len = {len(data)};", ""]
    return "\n".join(lines)


def write_project(out):
    key, cert, cn, serial = project_key()
    proj = capsule(key, cert, cn, serial)
    open(os.path.join(out, "capsule-project.cap"), "wb").write(proj)
    open(os.path.join(out, "capsule-project.esl"), "wb").write(esl(CERT_X509, [cert]))
    open(os.path.join(out, "capsule-project-pub.der"), "wb").write(cert)
    open(os.path.join(out, "capsule_project_blob.h"), "w").write(
        c_header("capsule_project_blob", proj))
    return len(proj), len(cert)


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "--print-recipe":
        sys.stdout.write(RECIPE)
        return
    if len(sys.argv) >= 3 and sys.argv[1] == "--sign-project":
        out_cap = sys.argv[2]
        key, cert, cn, serial = project_key()
        data = capsule(key, cert, cn, serial)
        os.makedirs(os.path.dirname(os.path.abspath(out_cap)) or ".", exist_ok=True)
        open(out_cap, "wb").write(data)
        print(f"wrote project capsule {len(data)} bytes -> {out_cap}")
        return
    if len(sys.argv) < 2:
        print("usage: mkcapsule.py OUTDIR | --sign-project OUT.cap | --print-recipe",
              file=sys.stderr)
        sys.exit(2)
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    key_a, key_b = rsa_key(0x5153_0001), rsa_key(0x5153_0002)
    cert_a = certificate(key_a, "SquirrelBIOS test key A", 0xA1)
    cert_b = certificate(key_b, "SquirrelBIOS test key B", 0xB2)
    a = (key_a, cert_a, "SquirrelBIOS test key A", 0xA1)
    b = (key_b, cert_b, "SquirrelBIOS test key B", 0xB2)
    good, bad, persist = capsule(*a), capsule(*b), capsule(*a, flags=PERSIST)
    open(os.path.join(out, "capsule-good.cap"), "wb").write(good)
    open(os.path.join(out, "capsule-bad.cap"), "wb").write(bad)
    open(os.path.join(out, "capsule-persist.cap"), "wb").write(persist)
    open(os.path.join(out, "capsule_good_blob.h"), "w").write(c_header("capsule_good_blob", good))
    open(os.path.join(out, "capsule_bad_blob.h"), "w").write(c_header("capsule_bad_blob", bad))
    open(os.path.join(out, "capsule_persist_blob.h"), "w").write(
        c_header("capsule_persist_blob", persist))
    plen, clen = write_project(out)
    print(f"wrote good={len(good)} bad={len(bad)} persist={len(persist)} "
          f"project={plen} pub.der={clen} to {out}")


if __name__ == "__main__":
    main()
