# Design row -> cell rows: 1.5x stretch, rows 0-6 into cell rows 2-12,
# descenders (7, 8) into 13 and 14. Cell rows 0, 1 and 15 stay blank.
ROW_MAP = {0: (2, 3), 1: (4,), 2: (5, 6), 3: (7,), 4: (8, 9), 5: (10,),
           6: (11, 12), 7: (13,), 8: (14,)}


def cell(art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) in (7, 8, 9), rows
    assert all(len(r) == 5 for r in rows), rows
    out = [0] * 16
    for i, r in enumerate(rows):
        bits = 0
        for c in r:
            bits = (bits << 1) | (c == '#')
        byte = bits << 2            # columns 1-5 of 8
        byte |= byte >> 1           # two pixels wide: columns 1-6
        for y in ROW_MAP[i]:
            out[y] = byte
    return out


def main():
    print('; SquirrelBIOS VGA text font, 256 glyphs of 8x16. Original design.')
    print('; Generated by x86/mkfont.py from the drawings there; edit those,')
    print('; not this file.')
    print()
    print('font_8x16:')
    for code in range(256):
        ch = chr(code)
        rows = cell(GLYPHS[ch]) if ch in GLYPHS else [0] * 16
        name = repr(ch) if ch in GLYPHS else ''
        data = ', '.join(f'0x{b:02X}' for b in rows)
        print(f'    db {data}  ; 0x{code:02X} {name}'.rstrip())
    print('font_8x16_end:')


if __name__ == '__main__':
    main()
